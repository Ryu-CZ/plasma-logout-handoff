#!/usr/bin/env bash
# Test removal of chwd's retired EGL workaround without changing packages.
set -euo pipefail

action=${1:-trial}
[[ $# -le 1 && ( $action == trial || $action == --restore ) ]] || exit 2
[[ $(hostname -s) == vandal-tomt && -t 0 && -t 1 ]] || {
    echo 'Run this at a local terminal on Vandal.' >&2
    exit 1
}
if (( EUID != 0 )); then
    [[ -z ${SSH_CONNECTION:-} && ( $action == --restore || ${XDG_SESSION_TYPE:-} == wayland ) ]] || {
        echo 'Run the trial from local Plasma Wayland, not over SSH.' >&2
        exit 1
    }
    exec sudo /usr/bin/bash "$(realpath -- "$0")" "$action"
fi

files=(
    /usr/lib/systemd/user-environment-generators/20-nvidia-rtd3-workaround
    /etc/profile.d/nvidia-rtd3-workaround.sh
)
restore='
set -e
for file do
    dir=${file%/*}/.vandal-rtd3-trial
    backup=$dir/${file##*/}
    if [[ -e $backup ]]; then
        mv -T --update=none-fail -- "$backup" "$file"
    fi
    if [[ -d $dir ]]; then rmdir -- "$dir"; fi
done
'
if [[ $action == --restore ]]; then
    /usr/bin/bash -c "$restore" restore "${files[@]}"
    echo 'Original files restored if a trial was active. No service restarted.'
    exit
fi

unit=vandal-rtd3-cleanup-rollback
greeter_uid=$(id -u plasmalogin)
if ! systemctl is-active --quiet plasmalogin.service ||
   [[ $(systemctl show -p ActiveState --value "user@$greeter_uid.service") != inactive ]] ||
   [[ -e /run/systemd/user-environment-generators/${files[0]##*/} ]]; then
    echo 'The expected PLM baseline is not present. Nothing changed.' >&2
    exit 1
fi
for file in "${files[@]}"; do
    if [[ ! -f $file || -L $file || -e ${file%/*}/.vandal-rtd3-trial ]] ||
       pacman -Qo -- "$file" >/dev/null 2>&1 ||
       ! grep -Fq 'automatically generated by chwd' "$file" ||
       ! grep -Fq '__EGL_VENDOR_LIBRARY_FILENAMES=' "$file"; then
        echo "Unexpected file or existing backup: $file. Nothing changed." >&2
        exit 1
    fi
done

systemd-run --unit="$unit" --on-active=4min --timer-property=AccuracySec=1s --collect \
    /usr/bin/bash -c "$restore" restore "${files[@]}"
systemctl is-active --quiet "$unit.timer"
trap '/usr/bin/bash -c "$restore" restore "${files[@]}"' EXIT
for file in "${files[@]}"; do
    dir=${file%/*}/.vandal-rtd3-trial
    mkdir -m 700 -- "$dir"
    mv -T --update=none-fail -- "$file" "$dir/${file##*/}"
done
trap - EXIT

printf '\nTrial armed for four minutes. Use normal Log Out now.\n'
printf 'Sign back in once the greeter is ready, then lock and unlock once.\n'
printf 'The timer restores both files, but does not restart the greeter.\n'
